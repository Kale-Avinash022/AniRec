"""Strict JSON Mode Output Contract & Pydantic Validation Schemas (Step 34).

Enforces deterministic, strongly-typed JSON responses from LLM generation.
Validates the structural output against the recommendation contract and
strips markdown code blocks if present.

Usage::

    from src.generation.contract import RecommendationOutput, parse_llm_json

    output = parse_llm_json(raw_llm_string)
    for rec in output.recommendations:
        print(rec.title, rec.why)
"""

from __future__ import annotations

import json
import re
from typing import Optional

from pydantic import BaseModel, Field, ValidationError

from src.core.logger import logger


class RecommendedShow(BaseModel):
    """Pydantic model representing a single recommended anime title."""

    anilist_id: int = Field(description="AniList ID of the recommended show")
    title: str = Field(description="Title of the anime")
    year: Optional[int] = Field(None, description="Release year")
    why: str = Field(
        description="2-3 sentence reason citing matched tags and plot premise"
    )
    matched_attributes: list[str] = Field(
        default_factory=list,
        description="Specific community tags, genres, or studio attributes matched",
    )


class RecommendationOutput(BaseModel):
    """Strict top-level recommendation payload returned by the generator."""

    recommendations: list[RecommendedShow] = Field(
        default_factory=list,
        description="Ordered list of recommended shows matching the query",
    )
    reasoning_summary: str = Field(
        default="",
        description="Overview explanation of why these titles fit the user's intent",
    )


def extract_json_payload(raw_text: str) -> str:
    """Extract raw JSON string from potentially markdown-wrapped LLM output."""
    cleaned = raw_text.strip()
    # Strip markdown code fences if model returned ```json ... ```
    match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", cleaned, re.DOTALL)
    if match:
        return match.group(1).strip()

    # If starts with { and ends with }, return as is
    if cleaned.startswith("{") and cleaned.endswith("}"):
        return cleaned

    # Try finding first { and last }
    first_brace = cleaned.find("{")
    last_brace = cleaned.rfind("}")
    if first_brace != -1 and last_brace != -1 and last_brace > first_brace:
        return cleaned[first_brace : last_brace + 1]

    return cleaned


def parse_llm_json(raw_text: str) -> RecommendationOutput:
    """Parse and validate raw LLM string into a typed RecommendationOutput.

    Args:
        raw_text: Raw string generated by the LLM.

    Returns:
        Validated :class:`RecommendationOutput`.

    Raises:
        ValueError: If the string cannot be parsed as valid JSON or violates schema.
    """
    json_str = extract_json_payload(raw_text)
    try:
        data = json.loads(json_str)
    except json.JSONDecodeError as exc:
        logger.error(f"Failed to parse LLM response as JSON: {exc} | Raw text: {raw_text[:200]}")
        raise ValueError(f"Invalid JSON in LLM response: {exc}") from exc

    try:
        return RecommendationOutput.model_validate(data)
    except ValidationError as exc:
        logger.error(f"LLM JSON schema validation failed: {exc}")
        raise ValueError(f"LLM output violated contract schema: {exc}") from exc
